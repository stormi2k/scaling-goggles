    процент = (выполнено / всего * 100) if всего > 0 else 0
    
    print(f"\nСтатус выполнения дня:")
    print(f"Выполнено задач: {выполнено} из {всего}")
    print(f"Прогресс: [{'#' * int(процент/5)}{'.' * (20 - int(процент/5))}] {процент:.1f}%")

