def обработать_время():
    текущее = datetime.now().strftime("%H:%M")
    час = datetime.now().hour
    
    if 5 <= час < 12:
        период = "утро"
    elif 12 <= час < 17:
        период = "день"
    elif 17 <= час < 22:
        период = "вечер"
    else:
        период = "ночь"
    
    return текущее, период

