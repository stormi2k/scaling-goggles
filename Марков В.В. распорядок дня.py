import time
from datetime import datetime

class Действие:
    def __init__(self, время, название, описание):
        self.время = время
        self.название = название
        self.описание = описание
    
    def выполнить(self):
        return f"{self.время} - {self.название}: {self.описание}"

class ДневнойПлан:
    def __init__(self, владелец):
        self.владелец = владелец
        self.расписание = []
    
    def добавить_задачу(self, задача):
        self.расписание.append(задача)
    
    def показать_расписание(self):
        print(f"\n{'='*50}")
        print(f"Распорядок дня для: {self.владелец}")
        print(f"Дата: {datetime.now().strftime('%d.%m.%Y')}")
        print(f"{'='*50}\n")
        
        for i, задача in enumerate(self.расписание, 1):
            print(f"{i}. {задача.выполнить()}")
        
        self.показать_статистику()
    
    def показать_статистику(self):
        всего = len(self.расписание)
        print(f"\nВсего задач: {всего}")
        print(f"Первая задача: {self.расписание[0].время if self.расписание else 'нет'}")
        print(f"Последняя задача: {self.расписание[-1].время if self.расписание else 'нет'}")
        print("-" * 30)

